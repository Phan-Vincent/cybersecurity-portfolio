"""
run_lab.py
Runs every Sigma rule against every scenario and checks each scenario raised exactly
the detections it expects (and the benign baseline raised none).

    python src/run_lab.py                 # validate; exit 1 on any miss or false positive
    python src/run_lab.py --write-docs    # also regenerate docs/coverage.md
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).parent))
from sigma_lite import evaluate, load_rules  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "rules"
DATA = ROOT / "data"
COVERAGE = ROOT / "docs" / "coverage.md"
TECHNIQUE = re.compile(r"^attack\.(t\d{4}(?:\.\d{3})?)$")
TACTICS = {"reconnaissance", "resource-development", "initial-access", "execution", "persistence",
           "privilege-escalation", "defense-evasion", "credential-access", "discovery", "lateral-movement",
           "collection", "command-and-control", "exfiltration", "impact"}


def load_scenarios() -> list[dict]:
    with open(DATA / "scenarios.yml", encoding="utf-8") as fh:
        scenarios = yaml.safe_load(fh)
    for sc in scenarios:
        path = DATA / "scenarios" / sc["file"]
        sc["events"] = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]
    return scenarios


def run(rules=None, scenarios=None) -> list[dict]:
    rules = rules if rules is not None else load_rules(RULES)
    scenarios = scenarios if scenarios is not None else load_scenarios()
    results = []
    for sc in scenarios:
        alerts = evaluate(rules, sc["events"])
        fired = sorted({a.rule_name for a in alerts})
        expected = sorted(sc["expect"])
        results.append({"file": sc["file"], "story": sc["story"], "events": len(sc["events"]),
                        "alerts": alerts, "fired": fired, "expected": expected,
                        "missed": sorted(set(expected) - set(fired)),
                        "unexpected": sorted(set(fired) - set(expected))})
    return results


def coverage_markdown(rules, results) -> str:
    detected_in = defaultdict(list)
    for r in results:
        for name in r["fired"]:
            detected_in[name].append(r["file"].removesuffix(".jsonl"))
    rows = []
    for rule in sorted(rules, key=lambda x: x.name):
        if rule.level == "informational":
            continue  # building blocks
        techniques = [m.group(1).upper() for t in rule.tags if (m := TECHNIQUE.match(t))]
        tactics = [t.split(".", 1)[1] for t in rule.tags if t.split(".", 1)[1] in TACTICS]
        links = ", ".join(f"[{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/)" for t in techniques)
        source = "correlation" if rule.is_correlation else "/".join(
            v for k, v in rule.data["logsource"].items() if k in ("product", "category", "service"))
        rows.append(f"| `{rule.name}` | {rule.level} | {', '.join(tactics)} | {links} | {source} | "
                    f"{', '.join(detected_in[rule.name]) or '**not exercised**'} |")
    lines = [
        "# ATT&CK coverage",
        "",
        "Generated by `python src/run_lab.py --write-docs`; a test fails if this file is out of date.",
        "",
        "| Rule | Level | Tactic | Technique | Log source | Proven by scenario |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "## Scenario results",
        "",
        "| Scenario | Events | Expected | Fired | Result |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        ok = not r["missed"] and not r["unexpected"]
        lines.append(f"| {r['file'].removesuffix('.jsonl')} | {r['events']} | {len(r['expected'])} | "
                     f"{len(r['fired'])} | {'pass' if ok else 'FAIL'} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("--write-docs", action="store_true", help="regenerate docs/coverage.md")
    args = parser.parse_args(argv)

    rules = load_rules(RULES)
    results = run(rules)
    failed = False
    for r in results:
        ok = not r["missed"] and not r["unexpected"]
        failed |= not ok
        print(f"[{'PASS' if ok else 'FAIL'}] {r['file']}: {len(r['alerts'])} alert(s) from {len(r['fired'])} rule(s)")
        for alert in r["alerts"]:
            group = f" {alert.group}" if alert.group else ""
            print(f"       {alert.level:<8} {alert.rule_name}{group} <- {', '.join(alert.event_ids[:3])}"
                  f"{' ...' if len(alert.event_ids) > 3 else ''}")
        for name in r["missed"]:
            print(f"       MISSED     {name}")
        for name in r["unexpected"]:
            print(f"       FALSE POSITIVE {name}")
    if args.write_docs:
        COVERAGE.parent.mkdir(exist_ok=True)
        COVERAGE.write_text(coverage_markdown(rules, results), encoding="utf-8")
        print(f"wrote {COVERAGE.relative_to(ROOT)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
